        self.cell(0, 6, "GENERATED ON", new_x="LMARGIN", new_y="NEXT")
        self.set_x(32)
        self.set_font("helvetica", "", 9.5)
        self.set_text_color(55, 66, 78)
        self.cell(0, 6, datetime.datetime.now().astimezone().strftime("%Y-%m-%d %H:%M:%S %Z"), new_x="LMARGIN", new_y="NEXT")

        self.set_y(230)
