def _is_table_start(lines: list[str], index: int) -> bool:
    if index + 1 >= len(lines):
        return False
    current = lines[index].strip()
    following = lines[index + 1].strip()
    return "|" in current and _is_markdown_table_separator(following)


def markdown_to_pdf(markdown_str: str, output_path: str | Path, case_id: str):
    markdown_str = _pdf_safe_text(markdown_str)
    case_id = _pdf_safe_text(case_id)
    pdf = ForensicPDF()
    title_match = re.search(r"^\*\*Case title:\*\*\s*(.+)$", markdown_str, re.MULTILINE)
    case_title = title_match.group(1).strip() if title_match else "Case Investigation Findings"
    pdf.build_title_page("Case Investigation Findings", case_id, case_title=case_title)
    pdf.add_page()
    pdf.set_y(23)

    lines = markdown_str.split("\n")
    in_code_block = False
    code_content: list[str] = []
    index = 0

    while index < len(lines):
        line = lines[index]
        stripped = line.strip()

        if _is_table_start(lines, index):
            table_rows: list[list[str]] = []
            table_rows.append(_split_markdown_table_row(lines[index]))
            index += 2  # consume heading and Markdown alignment row
            while index < len(lines) and "|" in lines[index] and lines[index].strip():
                table_rows.append(_split_markdown_table_row(lines[index]))
                index += 1
            _render_markdown_table(pdf, table_rows)
            continue

        if stripped.startswith("```"):
            if in_code_block:
                in_code_block = False
                pdf.set_font("courier", "", 8.5)
                pdf.set_fill_color(246, 248, 250)
                pdf.set_text_color(35, 45, 58)
                pdf.multi_cell(0, 4.5, "\n".join(code_content), border=1, fill=True)
                pdf.ln(4)
                code_content = []
            else:
                in_code_block = True
            index += 1
            continue

        if in_code_block:
            code_content.append(line)
            index += 1
            continue

        if stripped.startswith("# "):
            pdf.ln(6)
            pdf.set_font("helvetica", "B", 19)
            pdf.set_text_color(0, 51, 84)
            pdf.multi_cell(0, 9, _clean_inline_markdown(stripped[2:]))
            pdf.ln(3)
        elif stripped.startswith("## "):
            pdf.ln(5)
            pdf.set_font("helvetica", "B", 13)
            pdf.set_text_color(0, 51, 84)
            pdf.multi_cell(0, 7, _clean_inline_markdown(stripped[3:]))
            pdf.set_draw_color(0, 82, 125)
            pdf.set_line_width(0.45)
            pdf.line(pdf.l_margin, pdf.get_y() + 1, pdf.w - pdf.r_margin, pdf.get_y() + 1)
            pdf.ln(4)
        elif stripped.startswith("### "):
            pdf.ln(3)
            pdf.set_font("helvetica", "B", 10.5)
            pdf.set_text_color(190, 125, 0)
            pdf.multi_cell(0, 6, _clean_inline_markdown(stripped[4:]))
            pdf.ln(1)
        elif stripped.startswith("> "):
            quote = _clean_inline_markdown(stripped[2:])
            pdf.set_font("helvetica", "I", 9)
            pdf.set_text_color(45, 62, 78)
            pdf.set_fill_color(240, 245, 249)
            pdf.set_draw_color(0, 82, 125)
            x = pdf.get_x()
            pdf.set_x(x + 2)
            pdf.multi_cell(pdf.epw - 2, 5, quote, border="L", fill=True)
            pdf.ln(2)
        elif stripped.startswith("* ") or stripped.startswith("- "):
            bullet_text = _clean_inline_markdown(stripped[2:])
            pdf.set_font("helvetica", "", 9.5)
            pdf.set_text_color(40, 50, 60)
            pdf.cell(5, 5, "-", align="L")
            pdf.multi_cell(0, 5, bullet_text)
            pdf.ln(1)
        elif re.match(r"^\d+\.\s", stripped):
            match = re.match(r"^(\d+)\.\s(.*)", stripped)
            number, item_text = match.groups()
            pdf.set_font("helvetica", "", 9.5)
            pdf.set_text_color(40, 50, 60)
            pdf.cell(8, 5, f"{number}.", align="L")
            pdf.multi_cell(0, 5, _clean_inline_markdown(item_text))
            pdf.ln(1)
        elif stripped:
            pdf.set_font("helvetica", "", 9.5)
            pdf.set_text_color(40, 50, 60)
            pdf.multi_cell(0, 5, _clean_inline_markdown(stripped))
            pdf.ln(2)
        else:
            pdf.ln(1.5)

        index += 1

    if in_code_block and code_content:
        pdf.set_font("courier", "", 8.5)
        pdf.multi_cell(0, 4.5, "\n".join(code_content), border=1)

    output_path = Path(output_path)
    output_path.parent.mkdir(parents=True, exist_ok=True)
    pdf.output(str(output_path))
    print(f"[PDF Generator] Saved PDF report to {output_path}")
    return str(output_path)
