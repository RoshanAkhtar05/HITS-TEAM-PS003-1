"""PDF renderer for deterministic TATHYA-DF investigation reports.

Supports the Markdown subset generated by ``api.case_report`` including
headings, paragraphs, lists, code blocks, blockquotes and pipe tables.
"""
from __future__ import annotations

import re
from pathlib import Path
from typing import Iterable

from fpdf import FPDF
from fpdf.enums import TableBordersLayout, TableCellFillMode
from fpdf.fonts import FontFace


def _pdf_safe_text(value: str) -> str:
    """Map report punctuation to characters supported by FPDF core fonts."""
    replacements = {
        "—": "-", "–": "-", "−": "-", "→": "->", "←": "<-", "↔": "<->",
        "“": '"', "”": '"', "‘": "'", "’": "'", "…": "...",
        "₹": "INR ", "•": "-", "✓": "[OK]", "✗": "[X]", "≤": "<=", "≥": ">=",
        "≠": "!=", "≈": "~", "—": "-", " ": " ",
    }
    text = str(value)
    for original, replacement in replacements.items():
        text = text.replace(original, replacement)
    # FPDF core fonts are Latin-1. Keep report generation resilient when source
    # evidence includes unsupported glyphs; source files remain unchanged.
    return text.encode("latin-1", errors="replace").decode("latin-1")


def _clean_inline_markdown(value: str) -> str:
    value = value.strip()
    value = re.sub(r"\*\*(.*?)\*\*", r"\1", value)
    value = re.sub(r"(?<!\*)\*(?!\*)(.*?)\*(?!\*)", r"\1", value)
    value = value.replace("`", "")
    value = value.replace("\\|", "|")
    return value


def _split_markdown_table_row(line: str) -> list[str]:
    """Split one pipe-table row while respecting escaped pipe characters."""
    text = line.strip()
    if text.startswith("|"):
        text = text[1:]
    if text.endswith("|") and not text.endswith("\\|"):
        text = text[:-1]
    cells: list[str] = []
    current: list[str] = []
    escaped = False
    for char in text:
        if char == "|" and not escaped:
            cells.append(_clean_inline_markdown("".join(current)))
            current = []
        else:
            current.append(char)
        if char == "\\" and not escaped:
            escaped = True
        else:
            escaped = False
    cells.append(_clean_inline_markdown("".join(current)))
    return cells


def _is_markdown_table_separator(line: str) -> bool:
    cells = _split_markdown_table_row(line)
    return bool(cells) and all(re.fullmatch(r":?-{3,}:?", cell.replace(" ", "")) for cell in cells)


def _table_column_widths(headers: list[str], rows: list[list[str]]) -> tuple[float, ...]:
    """Return readable relative widths, with useful defaults for report tables."""
    count = len(headers)
    normalized_headers = [header.casefold() for header in headers]
    if count == 6 and "source category" in normalized_headers and "relationships" in normalized_headers:
        return (15, 19, 13, 10, 14, 29)
    if count >= 7 and "relationship" in " ".join(normalized_headers):
        return (17, 14, 17, 13, 9, 12, 18)[:count]

    max_lengths = []
    for index, header in enumerate(headers):
        longest = len(header)
        for row in rows:
            if index < len(row):
                longest = max(longest, min(len(row[index]), 42))
        max_lengths.append(max(7, min(longest, 34)) ** 0.72)
    total = sum(max_lengths) or 1
    return tuple(round((weight / total) * 100, 2) for weight in max_lengths)


def _render_markdown_table(pdf: FPDF, rows: list[list[str]]) -> None:
    if not rows:
        return
    column_count = max(len(row) for row in rows)
    normalized = [row + [""] * (column_count - len(row)) for row in rows]
    headers, body = normalized[0], normalized[1:]
    widths = _table_column_widths(headers, body)
    font_size = 7.0 if column_count >= 7 else (7.5 if column_count >= 6 else 8.5)

    pdf.ln(2)
    pdf.set_font("helvetica", "", font_size)
    pdf.set_text_color(35, 45, 58)
    heading_style = FontFace(
        family="helvetica",
        emphasis="B",
        size_pt=font_size,
        color=(255, 255, 255),
        fill_color=(0, 51, 84),
    )
    with pdf.table(
        width=pdf.epw,
        col_widths=widths,
        first_row_as_headings=True,
        headings_style=heading_style,
        cell_fill_color=(246, 248, 251),
        cell_fill_mode=TableCellFillMode.ROWS,
        borders_layout=TableBordersLayout.HORIZONTAL_LINES,
        line_height=4.4 if column_count >= 6 else 5.0,
        padding=(1.5, 1.7),
        text_align="LEFT",
        repeat_headings=1,
    ) as table:
        table.row(headers)
        for row in body:
            table.row(row)
    pdf.ln(4)


class ForensicPDF(FPDF):
    def __init__(self):
        super().__init__(orientation="P", unit="mm", format="A4")
        self.set_margins(18, 18, 18)
        self.set_auto_page_break(auto=True, margin=18)
        self.set_title("TATHYA-DF Investigation Report")
        self.set_author("TATHYA-DF Digital Forensics & Cyber Intelligence Division")
        self.set_subject("Demonstration / analyst review copy")

    def header(self):
        if self.page_no() > 1:
            self.set_y(9)
            self.set_font("helvetica", "I", 7.5)
            self.set_text_color(100, 112, 124)
            self.cell(120, 6, "TATHYA-DF  /  FORENSIC INTELLIGENCE REPORT", align="L")
            self.cell(0, 6, f"PAGE {self.page_no()}", align="R")
            self.set_y(17)
            self.set_draw_color(205, 214, 223)
            self.set_line_width(0.25)
            self.line(self.l_margin, self.get_y(), self.w - self.r_margin, self.get_y())
            self.ln(5)

    def footer(self):
        if self.page_no() > 1:
            self.set_y(-13)
            self.set_font("helvetica", "I", 7.5)
            self.set_text_color(120, 130, 140)
            self.cell(0, 7, "DEMONSTRATION REPORT - INVESTIGATOR REVIEW COPY", align="C")

    def build_title_page(self, title: str, case_id: str, case_title: str | None = None):
        import datetime

        self.add_page()
        # Compact masthead and case summary: use the cover page intentionally,
        # avoiding the large empty area in the previous layout.
        self.set_fill_color(0, 42, 72)
        self.rect(0, 0, self.w, 58, "F")
        self.set_xy(20, 17)
        self.set_font("helvetica", "B", 14)
        self.set_text_color(255, 255, 255)
        self.cell(0, 8, "TATHYA-DF", new_x="LMARGIN", new_y="NEXT")
        self.set_x(20)
        self.set_font("helvetica", "", 8)
        self.set_text_color(198, 216, 230)
        self.cell(0, 6, "DIGITAL FORENSICS & CYBER INTELLIGENCE", new_x="LMARGIN", new_y="NEXT")
        self.set_draw_color(254, 183, 0)
        self.set_line_width(1.2)
        self.line(20, 52, 66, 52)

        self.set_y(73)
        self.set_font("helvetica", "B", 21)
        self.set_text_color(0, 51, 84)
        self.multi_cell(0, 10, "CASE INVESTIGATION REPORT", align="C")
        self.set_draw_color(254, 183, 0)
        self.set_line_width(0.8)
        self.line(54, self.get_y() + 4, self.w - 54, self.get_y() + 4)

        self.set_y(99)
        self.set_font("helvetica", "B", 8.5)
        self.set_text_color(88, 103, 117)
        self.cell(0, 6, "INVESTIGATION", align="C", new_x="LMARGIN", new_y="NEXT")
        self.set_font("helvetica", "B", 14)
        self.set_text_color(36, 48, 60)
        self.multi_cell(0, 8, _pdf_safe_text(case_title or title), align="C")

        self.set_y(124)
        self.set_font("helvetica", "B", 8)
        self.set_text_color(88, 103, 117)
        self.cell(0, 6, "CASE IDENTIFIER", align="C", new_x="LMARGIN", new_y="NEXT")
        self.set_font("helvetica", "", 9.5)
        self.set_text_color(55, 66, 78)
        self.multi_cell(0, 6, _pdf_safe_text(case_id), align="C")

        self.set_y(157)
        self.set_fill_color(244, 247, 250)
        self.set_draw_color(218, 225, 232)
        self.rect(24, 157, self.w - 48, 55, "DF")
        # Keep all text inset within the metadata card; FPDF's LMARGIN cursor
        # reset is intentionally avoided so labels do not escape the card.
        self.set_xy(32, 164)
        self.set_font("helvetica", "B", 8.5)
        self.set_text_color(0, 51, 84)
        self.cell(0, 6, "REPORT CLASSIFICATION", new_x="LMARGIN", new_y="NEXT")
        self.set_x(32)
        self.set_font("helvetica", "", 9.5)
        self.set_text_color(55, 66, 78)
        self.cell(0, 6, "DEMONSTRATION / REVIEW COPY", new_x="LMARGIN", new_y="NEXT")
        self.set_x(32)
        self.set_font("helvetica", "B", 8.5)
